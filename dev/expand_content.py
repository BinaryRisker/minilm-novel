def main():
    n = 0
    for prefix, anchor, marker, block in JOBS:
        fn = next((f for f in os.listdir(CONTENT)
                   if f.startswith(prefix) and f.endswith('.md')), None)
        if not fn:
            print('✗ 找不到', prefix)
            continue
        path = os.path.join(CONTENT, fn)
        t = open(path, encoding='utf-8').read()
        if marker in t:
            print(f'= 已存在，跳过 {prefix}')
            continue
        if anchor not in t:
            print(f'✗ 锚点未命中 {prefix}: {anchor[:20]}')
            continue
        t = t.replace(anchor, anchor + '\n' + block.strip() + '\n', 1)
        open(path, 'w', encoding='utf-8').write(t)
        n += 1
        print('✓', prefix, fn)
    print(f'\n完成：{n} 处扩充')
    return 0


if __name__ == '__main__':
    sys.exit(main())
